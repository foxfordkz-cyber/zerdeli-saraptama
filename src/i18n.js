export const dictionaries = { kk, ru };

// Russian needs plural forms after numbers; Kazakh does not.
function ruPlural(n, one, few, many) {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

const ruCounts = {
  resultsCount: (n) => `${n} ${ruPlural(n, 'комментарий', 'комментария', 'комментариев')}`,
  docsCount: (n) => `${n} ${ruPlural(n, 'документ', 'документа', 'документов')}`,
  statDocs: (n) => ruPlural(n, 'документ', 'документа', 'документов'),
  statSubjects: (n) => ruPlural(n, 'направление', 'направления', 'направлений'),
  kpiExpertsSub: (n) => `из ${n} ${ruPlural(n, 'школы', 'школ', 'школ')}`,
};

export function translate(lang, key, vars = {}) {
  if (lang === 'ru' && ruCounts[key] && typeof vars.n === 'number') return ruCounts[key](vars.n);
  const s = dictionaries[lang]?.[key] ?? dictionaries.kk[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export const LangContext = createContext({ lang: 'kk', t: (k, v) => translate('kk', k, v), setLang: () => {} });

export function useI18n() {
  return useContext(LangContext);
}

export function localeFor(lang) {
  return lang === 'ru' ? 'ru-RU' : 'kk-KZ';
}
